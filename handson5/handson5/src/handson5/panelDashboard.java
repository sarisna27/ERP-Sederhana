    private void btnPilihFotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPilihFotoActionPerformed
        // TODO add your handling code here:
        JFileChooser chooser = new JFileChooser();
        chooser.setDialogTitle("Pilih Foto Absen");

        int hasil = chooser.showOpenDialog(this);

        if (hasil == JFileChooser.APPROVE_OPTION) {
            fileTerpilih = chooser.getSelectedFile();

            ImageIcon icon = new ImageIcon(fileTerpilih.getAbsolutePath());
            Image img = icon.getImage().getScaledInstance(
                    lblPreviewFoto.getWidth(),
                    lblPreviewFoto.getHeight(),
                    Image.SCALE_SMOOTH
            );

            lblPreviewFoto.setIcon(new ImageIcon(img));
        }
    }//GEN-LAST:event_btnPilihFotoActionPerformed

    private void btnSimpanFotoActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSimpanFotoActionPerformed
        // TODO add your handling code here:
        if (fileTerpilih == null) {
            JOptionPane.showMessageDialog(this, "Pilih foto terlebih dahulu!");
            return;
        }

        try {
            File folder = new File("foto_absen");

            if (!folder.exists()) {
                folder.mkdir();
            }

            String namaFileBaru = System.currentTimeMillis() + "_" + fileTerpilih.getName();
            File tujuan = new File(folder, namaFileBaru);

            Files.copy(
                    fileTerpilih.toPath(),
                    tujuan.toPath(),
                    StandardCopyOption.REPLACE_EXISTING
            );

            String sql = "INSERT INTO foto_absen (nama_file, path_file) VALUES (?, ?)";
            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, namaFileBaru);
            pst.setString(2, tujuan.getAbsolutePath());
            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Foto absen berhasil diupload!");

            lblPreviewFoto.setIcon(null);
            fileTerpilih = null;

            tampilDataFotoAbsen();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal upload foto: " + e.getMessage());
        }
    }//GEN-LAST:event_btnSimpanFotoActionPerformed


