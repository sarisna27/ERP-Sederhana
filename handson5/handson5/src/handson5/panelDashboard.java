    private void tampilDataFotoAbsen() {
        DefaultTableModel model = new DefaultTableModel() {
            @Override
            public Class<?> getColumnClass(int column) {
                if (column == 4) {
                    return ImageIcon.class;
                }
                return Object.class;
            }

            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        model.addColumn("ID Absen");
        model.addColumn("Nama File");
        model.addColumn("Path File");
        model.addColumn("Tanggal Upload");
        model.addColumn("Preview Foto");

        tblFotoAbsen.setModel(model);
        tblFotoAbsen.setRowHeight(80);

        try {
            Connection conn = Handson5.getKoneksi();
            String sql = "SELECT * FROM foto_absen ORDER BY id_absen DESC";

            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                String path = rs.getString("path_file");
                ImageIcon preview = null;

                File file = new File(path);

                if (file.exists()) {
                    ImageIcon icon = new ImageIcon(path);
                    Image img = icon.getImage().getScaledInstance(
                            80,
                            60,
                            Image.SCALE_SMOOTH
                    );
                    preview = new ImageIcon(img);
                }

                model.addRow(new Object[]{
                    rs.getInt("id_absen"),
                    rs.getString("nama_file"),
                    rs.getString("path_file"),
                    rs.getDate("tanggal_upload"),
                    preview
                });
            }

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menampilkan foto absen: " + e.getMessage());
        }
    }

