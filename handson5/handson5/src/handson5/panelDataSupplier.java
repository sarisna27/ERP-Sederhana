    private void isiBarangDipasok() {
        cmbBarangDipasok.removeAllItems();
        cmbBarangDipasok.addItem("-- Pilih Barang Dipasok --");

        try {
            String sql = "SELECT DISTINCT kategori_barang FROM barang";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                cmbBarangDipasok.addItem(rs.getString("kategori_barang"));
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal memuat barang dipasok: " + e.getMessage());
        }
    }
    private void tampilData() {
        model = new DefaultTableModel();
        model.addColumn("Kode Supplier");
        model.addColumn("Nama Supplier");
        model.addColumn("Barang Dipasok");
        model.addColumn("Nama Kontak");
        model.addColumn("No Handphone");
        model.addColumn("Alamat");

        tblSupplier.setModel(model);

        try {
            String sql = "SELECT * FROM supplier ORDER BY kode_supplier ASC";
            Statement st = conn.createStatement();
            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {
                model.addRow(new Object[]{
                    rs.getString("kode_supplier"),
                    rs.getString("nama_supplier"),
                    rs.getString("barang_dipasok"),
                    rs.getString("nama_kontak_supplier"),
                    rs.getString("no_handphone"),
                    rs.getString("alamat")
                });
            }
        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menampilkan data supplier: " + e.getMessage());
        }
    }
    private void bersih() {
        txtKodeSupplier.setText("");
        txtNamaSupplier.setText("");
        txtNamaKontak.setText("");
        txtNoHandphone.setText("");
        txtAlamat.setText("");

        if (cmbBarangDipasok.getItemCount() > 0) {
            cmbBarangDipasok.setSelectedIndex(0);
        }

        txtKodeSupplier.requestFocus();
    }
    private boolean validasiInput() {
        if (txtKodeSupplier.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Kode supplier harus diisi!");
            txtKodeSupplier.requestFocus();
            return false;
        }

        if (txtNamaSupplier.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama supplier harus diisi!");
            txtNamaSupplier.requestFocus();
            return false;
        }

        if (cmbBarangDipasok.getSelectedItem() == null || cmbBarangDipasok.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Barang dipasok harus dipilih!");
            cmbBarangDipasok.requestFocus();
            return false;
        }

        if (txtNamaKontak.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nama kontak supplier harus diisi!");
            txtNamaKontak.requestFocus();
            return false;
        }

        if (txtNoHandphone.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "No. handphone harus diisi!");
            txtNoHandphone.requestFocus();
            return false;
        }

        if (txtAlamat.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Alamat harus diisi!");
            txtAlamat.requestFocus();
            return false;
        }

        return true;
    }

