    private void txtSimpan1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSimpan1ActionPerformed
        if (txtKodeSupplier.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih data supplier yang ingin diedit!");
            return;
        }

        if (!validasiInput()) {
            return;
        }

        try {
            String sql = "UPDATE supplier SET "
                    + "nama_supplier = ?, "
                    + "barang_dipasok = ?, "
                    + "nama_kontak_supplier = ?, "
                    + "no_handphone = ?, "
                    + "alamat = ? "
                    + "WHERE kode_supplier = ?";

            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtNamaSupplier.getText());
            pst.setString(2, cmbBarangDipasok.getSelectedItem().toString());
            pst.setString(3, txtNamaKontak.getText());
            pst.setString(4, txtNoHandphone.getText());
            pst.setString(5, txtAlamat.getText());
            pst.setString(6, txtKodeSupplier.getText());

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Data supplier berhasil diedit!");
            tampilData();
            bersih();
            txtKodeSupplier.setEnabled(true);

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal mengedit data supplier: " + e.getMessage());
        }
    }//GEN-LAST:event_txtSimpan1ActionPerformed

    private void txtSimpanActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSimpanActionPerformed
        if (!validasiInput()) {
            return;
        }

        try {
            String sql = "INSERT INTO supplier "
                    + "(kode_supplier, nama_supplier, barang_dipasok, nama_kontak_supplier, no_handphone, alamat) "
                    + "VALUES (?, ?, ?, ?, ?, ?)";

            PreparedStatement pst = conn.prepareStatement(sql);
            pst.setString(1, txtKodeSupplier.getText());
            pst.setString(2, txtNamaSupplier.getText());
            pst.setString(3, cmbBarangDipasok.getSelectedItem().toString());
            pst.setString(4, txtNamaKontak.getText());
            pst.setString(5, txtNoHandphone.getText());
            pst.setString(6, txtAlamat.getText());

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this, "Data supplier berhasil disimpan!");
            tampilData();
            bersih();

        } catch (Exception e) {
            JOptionPane.showMessageDialog(this, "Gagal menyimpan data supplier: " + e.getMessage());
        }
    }//GEN-LAST:event_txtSimpanActionPerformed

    private void tblSupplierMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tblSupplierMouseClicked
        int baris = tblSupplier.getSelectedRow();

        if (baris != -1) {
            txtKodeSupplier.setText(tblSupplier.getValueAt(baris, 0).toString());
            txtNamaSupplier.setText(tblSupplier.getValueAt(baris, 1).toString());
            cmbBarangDipasok.setSelectedItem(tblSupplier.getValueAt(baris, 2).toString());
            txtNamaKontak.setText(tblSupplier.getValueAt(baris, 3).toString());
            txtNoHandphone.setText(tblSupplier.getValueAt(baris, 4).toString());
            txtAlamat.setText(tblSupplier.getValueAt(baris, 5).toString());

            txtKodeSupplier.setEnabled(false);
        }
    }//GEN-LAST:event_tblSupplierMouseClicked

    private void txtSimpan2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_txtSimpan2ActionPerformed

        if (txtKodeSupplier.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Pilih data supplier yang ingin dihapus!");
            return;
        }

        int konfirmasi = JOptionPane.showConfirmDialog(
                this,
                "Apakah Anda yakin ingin menghapus data supplier ini?",
                "Konfirmasi Hapus",
                JOptionPane.YES_NO_OPTION
        );

        if (konfirmasi == JOptionPane.YES_OPTION) {
            try {
                String sql = "DELETE FROM supplier WHERE kode_supplier = ?";
                PreparedStatement pst = conn.prepareStatement(sql);
                pst.setString(1, txtKodeSupplier.getText());
                pst.executeUpdate();

                JOptionPane.showMessageDialog(this, "Data supplier berhasil dihapus!");
                tampilData();
                bersih();
                txtKodeSupplier.setEnabled(true);

            } catch (Exception e) {
                JOptionPane.showMessageDialog(this, "Gagal menghapus data supplier: " + e.getMessage());
            }
        }
    }//GEN-LAST:event_txtSimpan2ActionPerformed

